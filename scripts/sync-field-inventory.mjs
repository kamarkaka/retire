// Regenerate current field mappings without rewriting the independent M00 oracles.
import { readFile, writeFile } from 'node:fs/promises';
import { fields, containers } from '../verification/reference/inventory.mjs';

const catalog = JSON.parse(
  await readFile('verification/config-fields.json', 'utf8'),
);
catalog.scope =
  'Current implemented configuration contract; frozen M00 oracles remain unchanged';
catalog.containers = containers;
catalog.fields = fields;
await writeFile(
  'verification/config-fields.json',
  JSON.stringify(catalog, null, 2) + '\n',
);
await writeFile(
  'src/config/fields.json',
  JSON.stringify(fields, null, 2) + '\n',
);
const cell = (value) =>
  String(value).replaceAll('|', '\\|').replaceAll('\n', ' ');
let matrix =
  '# Serialized configuration field matrix\n\nGenerated by `node scripts/sync-field-inventory.mjs` from the current contract in `reference/inventory.mjs`. All ' +
  fields.length +
  ' fields have browser editors and plain-English help popups; conditional inputs appear only when applicable. Frozen M00 inputs/oracles are preserved separately.\n\nDefaults describe optional algorithm/reference values; required household facts stay missing. `[]` denotes an array item. There are no holding settings or Holding profiles. The same paths are used internally and serialized.\n\n| Key / internal and TOML path | Type / unit | Builder section / control | Omission / default | Constraints / gates | Plain-English help | Spec |\n|---|---|---|---|---|---|---|\n';
for (const f of fields)
  matrix += `| \`${f.path}\` | ${cell(f.type)} / ${cell(f.unit)} | ${cell(f.builder_section)} / ${cell(f.builder_control)} | ${cell(f.omission)}; ${f.default_kind}: ${cell(JSON.stringify(f.default))} | ${cell(f.constraints)} ${cell(f.gates.join(', '))} | ${cell(f.description)} | ${f.spec_section} |\n`;
matrix += '\n## Container omissions\n\n';
for (const [key, value] of Object.entries(containers))
  matrix += `- \`${key}\`: ${value}\n`;
matrix +=
  '\n## Automated verification\n\n`npm run check` checks strict parsing, portable round trips, builder workflows, independent numerical cases, and the current inventory. No manual sign-off is required. Detailed evidence is in [implementation status](implementation-status.md). Everyone stays alive through the younger person’s Max age year (or the person’s, when alone); sex is descriptive. The household has one domicile country and one or two people. Social Security is excluded: no benefits are ever paid. Budget is the single aggregate medical base; care is always additional through the final horizon and has no end age/scope. CNY cash interest is intentionally omitted and may return in a future model.\n';
await writeFile('verification/config-field-matrix.md', matrix);
console.log(
  `Generated ${fields.length} current field mappings; independent oracles were not rewritten.`,
);
