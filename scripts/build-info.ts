import { writeFile } from 'node:fs/promises';
import { applicationInputsHash } from './build-inputs';
const revision = (await applicationInputsHash()).sha256;
await writeFile(
  'src/build-info.ts',
  `// Generated by scripts/build-info.ts. Hash excludes this file and the development harness.\nexport const BUILD_SOURCE_SHA256 =\n  '${revision}';\nexport const BUILD_VERSION =\n  '0.1.0+${revision}';\n`,
);
console.log(`Build source SHA-256: ${revision}`);
