import { readFile, writeFile } from 'node:fs/promises';
import { applicationInputsHash } from './build-inputs';
const revision = (await applicationInputsHash()).sha256;
const version = JSON.parse(await readFile('package.json', 'utf8')).version;
await writeFile(
  'src/build-info.ts',
  `// Generated by scripts/build-info.ts. Hash excludes this file and the development harness.\nexport const BUILD_SOURCE_SHA256 =\n  '${revision}';\nexport const BUILD_VERSION =\n  '${version}+${revision}';\nexport const BUILD_DISPLAY_VERSION = '${version}';\n`,
);
console.log(`Build source SHA-256: ${revision}`);
